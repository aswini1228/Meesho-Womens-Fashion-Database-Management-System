-- INNER JOIN: CUSTOMER AND ORDERS
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME, O.ORDER_ID, O.ORDER_STATUS
FROM CUSTOMER_DETAILS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID;

-- LEFT JOIN: ALL CUSTOMERS AND ORDERS
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME, O.ORDER_ID
FROM CUSTOMER_DETAILS C
LEFT JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID;

-- RIGHT JOIN: ALL ORDERS AND CUSTOMER DETAILS
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME, O.ORDER_ID
FROM CUSTOMER_DETAILS C
RIGHT JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID;

-- COMPLETE ORDER DETAILS
SELECT C.CUSTOMER_NAME, O.ORDER_ID, P.PRODUCT_NAME,
       P.PRICE, OD.QUANTITY, PAY.PAYMENT_METHOD,
       PAY.PAYMENT_STATUS
FROM CUSTOMER_DETAILS C
JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
JOIN ORDER_DETAILS OD ON O.ORDER_ID = OD.ORDER_ID
JOIN PRODUCTS P ON OD.PRODUCT_ID = P.PRODUCT_ID
LEFT JOIN PAYMENT PAY ON O.ORDER_ID = PAY.ORDER_ID;

-- CUSTOMER PURCHASE HISTORY
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME, O.ORDER_ID,
       P.PRODUCT_NAME, OD.QUANTITY, P.PRICE
FROM CUSTOMER_DETAILS C
JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
JOIN ORDER_DETAILS OD ON O.ORDER_ID = OD.ORDER_ID
JOIN PRODUCTS P ON OD.PRODUCT_ID = P.PRODUCT_ID
ORDER BY C.CUSTOMER_ID;

-- MULTI-TABLE BUSINESS REPORT
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME,
       COUNT(DISTINCT O.ORDER_ID) AS TOTAL_ORDERS,
       NVL(SUM(OD.QUANTITY * P.PRICE), 0) AS TOTAL_PURCHASE
FROM CUSTOMER_DETAILS C
LEFT JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
LEFT JOIN ORDER_DETAILS OD ON O.ORDER_ID = OD.ORDER_ID
LEFT JOIN PRODUCTS P ON OD.PRODUCT_ID = P.PRODUCT_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
ORDER BY TOTAL_PURCHASE DESC;

-- PAYMENT TRANSACTION REPORT
SELECT PAY.PAYMENT_ID, O.ORDER_ID, C.CUSTOMER_NAME,
       PAY.PAYMENT_METHOD, PAY.AMOUNT, PAY.PAYMENT_STATUS
FROM PAYMENT PAY
JOIN ORDERS O ON PAY.ORDER_ID = O.ORDER_ID
LEFT JOIN CUSTOMER_DETAILS C ON O.CUSTOMER_ID = C.CUSTOMER_ID
ORDER BY PAY.PAYMENT_ID;
