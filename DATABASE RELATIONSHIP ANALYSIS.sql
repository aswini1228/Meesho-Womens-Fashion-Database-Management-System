CREATE TABLE CUSTOMER_DETAILS (
    CUSTOMER_ID NUMBER(38) PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(70),
    PHONE VARCHAR2(10),
    CITY VARCHAR2(30),
    PERMANENT_RESIDENTIAL VARCHAR2(100)
);

CREATE TABLE CATEGORY (
    CATEGORY_ID NUMBER PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(50)
);

CREATE TABLE SELLER (
    SELLER_ID NUMBER PRIMARY KEY,
    SELLER_NAME VARCHAR2(70),
    EMAIL VARCHAR2(100),
    PHONE_NUMBER VARCHAR2(10),
    ADDRESS VARCHAR2(100)
);

CREATE TABLE PRODUCTS (
    PRODUCT_ID NUMBER PRIMARY KEY,
    PRODUCT_NAME VARCHAR2(100),
    PRICE NUMBER(10,2),
    STOCK NUMBER,
    SELLER_ID NUMBER,
    CATEGORY_ID NUMBER,
    FOREIGN KEY (SELLER_ID) REFERENCES SELLER(SELLER_ID),
    FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(CATEGORY_ID)
);

CREATE TABLE ORDERS (
    ORDER_ID NUMBER PRIMARY KEY,
    CUSTOMER_ID NUMBER(38),
    ORDER_DATE DATE,
    TOTAL_AMOUNT NUMBER(10,2),
    ORDER_STATUS VARCHAR2(30),
    FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER_DETAILS(CUSTOMER_ID)
);

CREATE TABLE ORDER_DETAILS (
    ORDER_DETAIL_ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER,
    PRODUCT_ID NUMBER,
    QUANTITY NUMBER,
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID),
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID)
);

CREATE TABLE PAYMENT (
    PAYMENT_ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER,
    PAYMENT_METHOD VARCHAR2(30),
    PAYMENT_STATUS VARCHAR2(30),
    PAYMENT_DATE DATE,
    AMOUNT NUMBER(10,2),
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID)
);

CREATE TABLE DELIVERY (
    DELIVERY_ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER,
    DELIVERY_STATUS VARCHAR2(30),
    DELIVERY_DATE DATE,
    DELIVERY_ADDRESS VARCHAR2(100),
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID)
);

