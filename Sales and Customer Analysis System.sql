1.1 COUNT()
Find the total number of orders:
SELECT COUNT(*) AS TOTAL_ORDERS
FROM ORDERS;
1.2 SUM()
Find the total sales amount:
SELECT SUM(TOTAL_AMOUNT) AS TOTAL_SALES
FROM ORDERS;
1.3 AVG()
Find the average order amount:
SELECT AVG(TOTAL_AMOUNT) AS AVERAGE_ORDER_AMOUNT
FROM ORDERS;
1.4 MIN()
Find the lowest order amount:
SELECT MIN(TOTAL_AMOUNT) AS LOWEST_ORDER_AMOUNT
FROM ORDERS;
1.5 MAX()
Find the highest order amount:
SELECT MAX(TOTAL_AMOUNT) AS HIGHEST_ORDER_AMOUNT
FROM ORDERS;

2. Generate Total Sales Reports

SELECT
    COUNT(ORDER_ID) AS TOTAL_ORDERS,
    SUM(TOTAL_AMOUNT) AS TOTAL_SALES,
    AVG(TOTAL_AMOUNT) AS AVERAGE_SALES
FROM ORDERS;

2.1 Customer-wise Sales Report

SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME,
       SUM(O.TOTAL_AMOUNT) AS TOTAL_PURCHASE_AMOUNT
FROM CUSTOMER_DETAILS C
JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
ORDER BY TOTAL_PURCHASE_AMOUNT DESC;

