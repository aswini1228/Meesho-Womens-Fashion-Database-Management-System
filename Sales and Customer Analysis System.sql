4. Identify Best-Selling Products

SELECT P.PRODUCT_ID, P.PRODUCT_NAME,
       SUM(OD.QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM MEESHO_PRODUCT P
JOIN ORDER_DETAILS OD ON P.PRODUCT_ID = OD.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY TOTAL_QUANTITY_SOLD DESC;

4.1 Product Sales Amount

SELECT P.PRODUCT_ID, P.PRODUCT_NAME,
       SUM(OD.QUANTITY) AS TOTAL_QUANTITY,
       SUM(P.PRICE * OD.QUANTITY) AS TOTAL_SALES_AMOUNT
FROM MEESHO_PRODUCT P
JOIN ORDER_DETAILS OD ON P.PRODUCT_ID = OD.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY TOTAL_SALES_AMOUNT DESC;

5. Category-wise Sales Analysis

SELECT C.CATEGORY_ID, C.CATEGORY_NAME,
       SUM(OD.QUANTITY) AS TOTAL_QUANTITY_SOLD,
       SUM(P.PRICE * OD.QUANTITY) AS CATEGORY_TOTAL_SALES
FROM CATEGORY C
JOIN MEESHO_PRODUCT P ON C.CATEGORY_ID = P.CATEGORY_ID
JOIN ORDER_DETAILS OD ON P.PRODUCT_ID = OD.PRODUCT_ID
GROUP BY C.CATEGORY_ID, C.CATEGORY_NAME
ORDER BY CATEGORY_TOTAL_SALES DESC;

6. Combined Business Sales Report

SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME, O.ORDER_ID,
       P.PRODUCT_NAME, CAT.CATEGORY_NAME,
       OD.QUANTITY, P.PRICE,
       (OD.QUANTITY * P.PRICE) AS TOTAL_AMOUNT
FROM CUSTOMER_DETAILS C
JOIN ORDERS O ON C.CUSTOMER_ID = O.CUSTOMER_ID
JOIN ORDER_DETAILS OD ON O.ORDER_ID = OD.ORDER_ID
JOIN MEESHO_PRODUCT P ON OD.PRODUCT_ID = P.PRODUCT_ID
JOIN CATEGORY CAT ON P.CATEGORY_ID = CAT.CATEGORY_ID
ORDER BY O.ORDER_ID;
